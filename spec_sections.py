#!/usr/bin/env python3
"""
SPEC SECTION MAP GENERATOR — GAP-2026-08-16-STEP5-SESSION-EXHAUSTION (Fix A).

Builds SPEC_SECTIONS.json: for every Framework_*.md, the line span of each of its own
'## ' and '### ' headers, plus the byte/token/view-call cost of each span.

WHY THIS EXISTS. Framework_PYQCore EC-P42. SKILL Rule 2 mandates reading every routed
.md IN FULL before any work. For trigger PYQExtract that is 556,834 B / ~139,208 tok /
>=36 view calls, MANDATORY, EVERY SESSION, on a step that is inherently multi-session.
In the reference incident 40 of session 1's 50 tool calls went to reading the
specification and the step stalled before its first productive operation. A session
that cannot clear the corpus never executes the synthesis, QV, summary or schema
sections, so it must not pay for them — but a reduced read is only safe if the ranges
are EXACT, and a hand-copied line number is a second definition of the file's own
structure that will drift on the first edit that adds a paragraph.

So the map is DERIVED, never declared. It is regenerated by gen_manifest.py, tracked in
MANIFEST.json by sha256, and verified by bootstrap.py like any other artefact. If the
spec changes and the map is not regenerated, the manifest check fails the build BEFORE
anybody reads a stale range.

THE MAP IS A READ AID AND NEVER A SECOND SOURCE OF TRUTH. It contains no spec content —
only line numbers into the verified file. Every read still comes out of the spec itself.
This is deliberate: a digest that carried copies of the fences would be a duplicate of
the source of truth inside a corpus whose entire integrity model is byte-verification.

    python3 spec_sections.py            # write SPEC_SECTIONS.json
    python3 spec_sections.py --check    # exit 1 if the committed map is stale
    python3 spec_sections.py --self-test
"""
