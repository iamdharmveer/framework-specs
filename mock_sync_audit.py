# ── MS-3 ────────────────────────────────────────────────────────────────
def check_stamp_parity(read=_read):
    problems = []
    text = read('Framework_MockTestAnalyse.md')
    hv = _header_version(text)
    if not hv:
        return ["Framework_MockTestAnalyse.md: no parseable header version"]
    mm = '.'.join(hv.split('.')[:2])
    pats = [r"framework_version: v(\d+\.\d+)",
            r"Framework_MockTestAnalyse v(\d+\.\d+)",
            r"Generated by Framework_MockTestAnalyse v(\d+\.\d+)"]
    body = _fences(text)
    for pat in pats:
        hits = list(re.finditer(pat, body))
        # PRESENCE (v2026.08.15.8). This check verifies LITERALS. A stamp built from
        # an f-string over a constant leaves nothing to match, so the pattern would
        # silently score 0 issues while verifying nothing — the same check-shaped
        # hole a non-compiling fence opened in audit_callgraph C6. A pattern that
        # matches NOTHING is therefore a finding in its own right: whoever removed
        # the last literal must either restore one or delete this pattern
        # deliberately, in its own commit, with a stated reason.
        if not hits:
            problems.append(f"Framework_MockTestAnalyse.md: no emitted stamp matches "
                            f"{pat!r} anywhere in this file's fences. MS-3 verifies "
                            f"LITERAL stamps; if they are now derived, this check is "
                            f"disarmed and reports success while checking nothing. "
                            f"Keep one literal per pattern, or remove the pattern on "
                            f"purpose.")
            continue
        for m in hits:
            if m.group(1) != mm:
                problems.append(f"Framework_MockTestAnalyse.md: emitted stamp "
                                f"{m.group(0)!r} != header major.minor v{mm} "
                                f"(the five-times-recurred stamp-drift class)")
    return problems


