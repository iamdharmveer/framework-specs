def _read(name, root=None):
    return open(os.path.join(root or HERE, name), encoding='utf-8').read()


def _fences(text):
    """All ```python / ```text fenced bodies as one concatenated string."""
    out = []
    for m in re.finditer(r'```(?:python|text)\n(.*?)\n```', text, re.S):
        out.append(m.group(1))
    return '\n'.join(out)


def _header_version(text):
    m = re.match(r'^#\s*\S+\s+v(\d+(?:\.\d+)+)', text)
    return m.group(1) if m else None


# ── MS-1 ────────────────────────────────────────────────────────────────
def check_pin_floor(read=_read, run=None):
    """Returns list of problem strings."""
    problems = []
    floors = {}   # flag -> max declared floor
    for spec in ('Framework_MockTestExplain.md', 'Framework_PYQExplain.md'):
        text = read(spec)
        _lines = text.split('\n')
        for i, line in enumerate(_lines, 1):
            window = line + ' ' + (_lines[i] if i < len(_lines) else '')
            low = window.lower()
            if 'ust print' in low and re.search(r'SELF-TEST: \d+/\d+ PASS', window):
                problems.append(f"{spec} L{i}: exact self-test count pinned on a "
                                f"'must print' line — use the FLOOR form (N/N "
                                f"PASS with N >= K); exact pins HALT healthy "
                                f"sessions when the engine grows fixtures")
        for m in re.finditer(r'SELF-TEST: N/N PASS["\s,]*(?:with N\s*[=>]+\s*total[^;)]*?)?(?:AND\s+)?N\s*>=\s*(\d+)', text):
            floors['--self-test'] = max(floors.get('--self-test', 0), int(m.group(1)))
        for m in re.finditer(r'N/N PASS[",\s]*(?:with)?\s*N\s*>=\s*(\d+)', text):
            pass  # generic floors handled per-flag below
        for m in re.finditer(r'self-test-audit[^\n]*?N\s*>=\s*(\d+)', text):
            floors['--self-test-audit'] = max(floors.get('--self-test-audit', 0),
                                              int(m.group(1)))
        for m in re.finditer(r'N\s*>=\s*(\d+)[^\n]*?(?:core|before any\s*$)', text):
            floors['--self-test'] = max(floors.get('--self-test', 0), int(m.group(1)))
    runner = run or _run_explain_engine
    for flag, floor in sorted(floors.items()):
        actual = runner(flag)
        if actual is None:
            problems.append(f"explain_engine.py {flag}: could not parse an "
                            f"N/N PASS banner from its output")
        elif actual < floor:
            problems.append(f"explain_engine.py {flag}: prints {actual} "
                            f"fixtures but a spec floor demands >= {floor}")
    return problems


def _run_explain_engine(flag):
    try:
        r = subprocess.run([sys.executable,
                            os.path.join(HERE, 'explain_engine.py'), flag],
                           capture_output=True, text=True, timeout=300)
        m = re.search(r'SELF-TEST: (\d+)/(\d+) PASS', r.stdout or '')
        if m and m.group(1) == m.group(2):
            return int(m.group(1))
    except Exception:
        pass
    return None


